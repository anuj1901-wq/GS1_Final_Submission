CREATE OR REPLACE VIEW
ANALYTICS.DASHBOARD_PRIORITY_SUMMARY AS

SELECT
    CUSTOMER_PRIORITY,
    COUNT(*) AS TOTAL_COMPANIES,

    ROUND(AVG(MAX_RENEWAL_SCORE), 2)
        AS AVG_RENEWAL_SCORE,

    SUM(TOTAL_GCPS) AS TOTAL_GCPS

FROM ANALYTICS.COMPANY_RENEWAL_RANKING

GROUP BY CUSTOMER_PRIORITY;

SELECT *
FROM ANALYTICS.DASHBOARD_PRIORITY_SUMMARY
ORDER BY AVG_RENEWAL_SCORE DESC NULLS LAST;