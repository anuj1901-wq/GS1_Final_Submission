WITH gtin_keys AS (
    SELECT DISTINCT GCP
    FROM STAGING.GTIN_CLEAN
    WHERE GCP IS NOT NULL
),
subscription_keys AS (
    SELECT DISTINCT GCP
    FROM STAGING.SUBSCRIPTIONS_CLEAN
    WHERE GCP IS NOT NULL
)

SELECT
    COUNT(*) AS TOTAL_DISTINCT_GCPS,

    COUNT_IF(g.GCP IS NOT NULL
             AND s.GCP IS NOT NULL) AS MATCHED_GCPS,

    COUNT_IF(g.GCP IS NOT NULL
             AND s.GCP IS NULL) AS GTIN_ONLY_GCPS,

    COUNT_IF(g.GCP IS NULL
             AND s.GCP IS NOT NULL) AS SUBSCRIPTION_ONLY_GCPS

FROM gtin_keys g
FULL OUTER JOIN subscription_keys s
    ON g.GCP = s.GCP;

