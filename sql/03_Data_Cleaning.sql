CREATE OR REPLACE VIEW
STAGING.SUBSCRIPTIONS_CLEAN AS

SELECT
    NULLIF(TRIM(GCP), '') AS GCP,
    NULLIF(TRIM(COMPANY_ID), '') AS COMPANY_ID,
    TRIM(COMPANY_NAME) AS COMPANY_NAME,
    UPPER(TRIM(PLAN)) AS PLAN,

    COALESCE(
        TRY_TO_DATE(
            NULLIF(TRIM(GCP_REGISTERED_DATE), ''),
            'DD-MM-YYYY'
        ),
        TRY_TO_DATE(
            NULLIF(TRIM(GCP_REGISTERED_DATE), ''),
            'DD/MM/YYYY'
        ),
        TRY_TO_DATE(
            NULLIF(TRIM(GCP_REGISTERED_DATE), ''),
            'YYYY-MM-DD'
        )
    ) AS REGISTERED_DATE,

    COALESCE(
        TRY_TO_DATE(
            NULLIF(TRIM(SUBSCRIPTION_START_DATE), ''),
            'DD-MM-YYYY'
        ),
        TRY_TO_DATE(
            NULLIF(TRIM(SUBSCRIPTION_START_DATE), ''),
            'DD/MM/YYYY'
        ),
        TRY_TO_DATE(
            NULLIF(TRIM(SUBSCRIPTION_START_DATE), ''),
            'YYYY-MM-DD'
        )
    ) AS START_DATE,

    COALESCE(
        TRY_TO_DATE(
            NULLIF(TRIM(SUBSCRIPTION_END_DATE), ''),
            'DD-MM-YYYY'
        ),
        TRY_TO_DATE(
            NULLIF(TRIM(SUBSCRIPTION_END_DATE), ''),
            'DD/MM/YYYY'
        ),
        TRY_TO_DATE(
            NULLIF(TRIM(SUBSCRIPTION_END_DATE), ''),
            'YYYY-MM-DD'
        )
    ) AS END_DATE,

    UPPER(TRIM(VALIDITY_STATUS)) AS VALIDITY_STATUS

FROM RAW.SUBSCRIPTIONS;


CREATE OR REPLACE VIEW
STAGING.GTIN_CLEAN AS

SELECT
    NULLIF(TRIM(GCP), '') AS GCP,
    NULLIF(TRIM(COMPANY_ID), '') AS COMPANY_ID,
    TRIM(COMPANY_NAME) AS COMPANY_NAME,

    NULLIF(TRIM(FIRST_GTIN), '') AS FIRST_GTIN,

    TRY_TO_TIMESTAMP_TZ(
        NULLIF(TRIM(FIRST_GTIN_CREATED_AT), '')
    ) AS FIRST_GTIN_DATE,

    NULLIF(TRIM(LAST_GTIN), '') AS LAST_GTIN,

    TRY_TO_TIMESTAMP_TZ(
        NULLIF(TRIM(LAST_GTIN_CREATED_AT), '')
    ) AS LAST_GTIN_DATE,

    TRY_TO_NUMBER(
        NULLIF(TRIM(TOTAL_GTINS), '')
    ) AS TOTAL_GTINS

FROM RAW.GTIN_ACTIVITY;

