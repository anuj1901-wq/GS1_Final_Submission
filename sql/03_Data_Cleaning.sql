SELECT
    COUNT_IF(
        NULLIF(TRIM(r.GCP_REGISTERED_DATE), '') IS NOT NULL
        AND c.REGISTERED_DATE IS NULL
    ) AS REGISTRATION_PARSE_FAILURES,

    COUNT_IF(
        NULLIF(TRIM(r.SUBSCRIPTION_END_DATE), '') IS NOT NULL
        AND c.END_DATE IS NULL
    ) AS EXPIRY_PARSE_FAILURES

FROM RAW.SUBSCRIPTIONS r
JOIN STAGING.SUBSCRIPTIONS_CLEAN c
    ON r.GCP IS NOT DISTINCT FROM c.GCP
   AND r.COMPANY_ID IS NOT DISTINCT FROM c.COMPANY_ID
   AND r.GCP_REGISTERED_DATE IS NOT DISTINCT FROM
       COALESCE(TO_VARCHAR(c.REGISTERED_DATE, 'DD-MM-YYYY'), r.GCP_REGISTERED_DATE);


SELECT
    COUNT_IF(
        REGISTERED_DATE IS NULL
    ) AS NULL_REGISTERED_DATES,

    COUNT_IF(
        START_DATE IS NULL
    ) AS NULL_START_DATES,

    COUNT_IF(
        END_DATE IS NULL
    ) AS NULL_END_DATES,

    COUNT_IF(
        END_DATE < START_DATE
    ) AS INVALID_SUBSCRIPTION_PERIODS

FROM STAGING.SUBSCRIPTIONS_CLEAN;

