USE WAREHOUSE GS1_WH;
USE DATABASE GS1_CUSTOMER_INTELLIGENCE;

SELECT
    'GTIN_ACTIVITY' AS SOURCE,
    GCP,
    COMPANY_ID,
    COMPANY_NAME,
    NULL AS PLAN,
    NULL AS END_DATE,
    TOTAL_GTINS,
    TO_VARCHAR(LAST_GTIN_DATE) AS LAST_GTIN_DATE
FROM STAGING.GTIN_CLEAN
WHERE GCP IN (
    '8904119127',
    '890853315',
    '8904434665'
)

UNION ALL

SELECT
    'SUBSCRIPTIONS' AS SOURCE,
    GCP,
    COMPANY_ID,
    COMPANY_NAME,
    PLAN,
    TO_VARCHAR(END_DATE) AS END_DATE,
    NULL AS TOTAL_GTINS,
    NULL AS LAST_GTIN_DATE
FROM STAGING.SUBSCRIPTIONS_CLEAN
WHERE GCP IN (
    '8904119127',
    '890853315',
    '8904434665'
)

ORDER BY GCP, SOURCE, COMPANY_ID;

SELECT
    COUNT_IF(
        NULLIF(TRIM(GCP_REGISTERED_DATE), '') IS NOT NULL
        AND COALESCE(
            TRY_TO_DATE(GCP_REGISTERED_DATE, 'DD-MM-YYYY'),
            TRY_TO_DATE(GCP_REGISTERED_DATE, 'DD/MM/YYYY'),
            TRY_TO_DATE(GCP_REGISTERED_DATE, 'YYYY-MM-DD')
        ) IS NULL
    ) AS REGISTRATION_PARSE_FAILURES,

    COUNT_IF(
        NULLIF(TRIM(SUBSCRIPTION_END_DATE), '') IS NOT NULL
        AND COALESCE(
            TRY_TO_DATE(SUBSCRIPTION_END_DATE, 'DD-MM-YYYY'),
            TRY_TO_DATE(SUBSCRIPTION_END_DATE, 'DD/MM/YYYY'),
            TRY_TO_DATE(SUBSCRIPTION_END_DATE, 'YYYY-MM-DD')
        ) IS NULL
    ) AS EXPIRY_PARSE_FAILURES

FROM RAW.SUBSCRIPTIONS;

SELECT
    GCP,
    COMPANY_ID,
    COMPANY_NAME,
    PLAN,
    REGISTERED_DATE,
    START_DATE,
    END_DATE,
    VALIDITY_STATUS
FROM STAGING.SUBSCRIPTIONS_CLEAN
WHERE END_DATE < START_DATE;


