USE WAREHOUSE GS1_WH;
USE DATABASE GS1_CUSTOMER_INTELLIGENCE;
USE SCHEMA ANALYTICS;

CREATE OR REPLACE VIEW ANALYTICS.GCP_SCORING AS

WITH prepared AS (
    SELECT
        *,
        CASE
            WHEN MATCH_STATUS = 'MATCHED'
             AND NOT COMPANY_ID_MISMATCH
             AND NOT INVALID_SUBSCRIPTION_PERIOD
             AND COMPANY_ID IS NOT NULL
             AND END_DATE IS NOT NULL
             AND REGISTERED_DATE <= AS_OF_DATE
             AND END_DATE >= REGISTERED_DATE
             AND COALESCE(TOTAL_GTINS, 0) >= 0
             AND (
                 LAST_ACTIVITY_DATE IS NULL
                 OR LAST_ACTIVITY_DATE <= AS_OF_DATE
             )
             AND (
                 FIRST_ACTIVITY_DATE IS NULL
                 OR FIRST_ACTIVITY_DATE <= AS_OF_DATE
             )
            THEN TRUE
            ELSE FALSE
        END AS IS_SCOREABLE

    FROM ANALYTICS.CUSTOMER_METRICS
),

components AS (
    SELECT
        *,

        -- Maximum: 40 points
        CASE
            WHEN NOT IS_SCOREABLE THEN NULL
            WHEN DAYS_TO_EXPIRY < 0 THEN 40
            WHEN DAYS_TO_EXPIRY <= 30 THEN 35
            WHEN DAYS_TO_EXPIRY <= 90 THEN 25
            ELSE 0
        END AS RENEWAL_URGENCY_POINTS,

        -- Maximum: 30 points
        CASE
            WHEN NOT IS_SCOREABLE THEN NULL
            WHEN ENGAGEMENT_SEGMENT = 'DORMANT' THEN 30
            WHEN ENGAGEMENT_SEGMENT = 'QUIET' THEN 20
            WHEN ENGAGEMENT_SEGMENT = 'ACTIVE' THEN 0
            WHEN ENGAGEMENT_SEGMENT = 'NEVER ACTIVATED' THEN 30
            ELSE 0
        END AS ENGAGEMENT_POINTS,

        -- Maximum: 20 points
        CASE
            WHEN NOT IS_SCOREABLE THEN NULL
            WHEN ADOPTION_SEGMENT = 'NEVER ACTIVATED'
                THEN 20
            WHEN ADOPTION_SEGMENT = 'OVER 90 DAYS'
                THEN 15
            WHEN ADOPTION_SEGMENT = '31-90 DAYS'
                THEN 8
            WHEN ADOPTION_SEGMENT = 'WITHIN 30 DAYS'
                THEN 0
            ELSE 0
        END AS ACTIVATION_POINTS,

        -- Maximum: 10 points
        CASE
            WHEN NOT IS_SCOREABLE THEN NULL
            WHEN TOTAL_GTINS = 0 THEN 10
            WHEN TOTAL_GTINS BETWEEN 1 AND 10 THEN 7
            WHEN TOTAL_GTINS BETWEEN 11 AND 50 THEN 4
            ELSE 0
        END AS USAGE_POINTS

    FROM prepared
),

scored AS (
    SELECT
        *,

        RENEWAL_URGENCY_POINTS
        + ENGAGEMENT_POINTS
        + ACTIVATION_POINTS
        + USAGE_POINTS AS RENEWAL_SCORE

    FROM components
)

SELECT
    *,

    CASE
        WHEN NOT IS_SCOREABLE THEN 'REVIEW REQUIRED'
        WHEN RENEWAL_SCORE >= 75 THEN 'CRITICAL'
        WHEN RENEWAL_SCORE >= 50 THEN 'HIGH'
        WHEN RENEWAL_SCORE >= 25 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS PRIORITY_SEGMENT,

    CASE
        WHEN NOT IS_SCOREABLE THEN 'DATA VALIDATION'
        WHEN DAYS_TO_EXPIRY < 0 THEN 'EXPIRED - REVIEW'
        WHEN ADOPTION_SEGMENT = 'NEVER ACTIVATED'
            THEN 'ONBOARDING SUPPORT'
        WHEN RENEWAL_SCORE >= 50 THEN 'RETENTION OUTREACH'
        ELSE 'STANDARD ENGAGEMENT'
    END AS RECOMMENDED_ACTION

FROM scored;


SELECT
    PRIORITY_SEGMENT,
    COUNT(*) AS TOTAL_GCPS,

    ROUND(AVG(RENEWAL_SCORE), 2)
        AS AVG_SCORE,

    MIN(RENEWAL_SCORE) AS MIN_SCORE,
    MAX(RENEWAL_SCORE) AS MAX_SCORE

FROM ANALYTICS.GCP_SCORING
GROUP BY PRIORITY_SEGMENT
ORDER BY AVG_SCORE DESC NULLS LAST;

SELECT
    COUNT(*) AS TOTAL_GCPS,
    COUNT_IF(IS_SCOREABLE) AS SCORED_GCPS,
    COUNT_IF(NOT IS_SCOREABLE) AS REVIEW_REQUIRED_GCPS,
    COUNT_IF(RENEWAL_SCORE > 100) AS SCORES_OVER_100,
    COUNT_IF(RENEWAL_SCORE < 0) AS SCORES_BELOW_ZERO

FROM ANALYTICS.GCP_SCORING;


CREATE OR REPLACE VIEW
ANALYTICS.COMPANY_RENEWAL_RANKING AS

WITH company_summary AS (
    SELECT
        COMPANY_ID,

        MAX(COMPANY_NAME) AS COMPANY_NAME,

        COUNT(*) AS TOTAL_GCPS,

        COUNT_IF(IS_SCOREABLE) AS SCORED_GCPS,

        COUNT_IF(NOT IS_SCOREABLE)
            AS REVIEW_REQUIRED_GCPS,

        SUM(COALESCE(TOTAL_GTINS, 0))
            AS TOTAL_GTINS,

        MAX(RENEWAL_SCORE)
            AS MAX_RENEWAL_SCORE,

        ROUND(AVG(RENEWAL_SCORE), 2)
            AS AVG_RENEWAL_SCORE,

        COUNT_IF(
            POST_EXPIRY_ACTIVITY_FLAG = 1
        ) AS POST_EXPIRY_GCPS,

        MIN(
            CASE
                WHEN DAYS_TO_EXPIRY >= 0
                THEN DAYS_TO_EXPIRY
            END
        ) AS NEAREST_UPCOMING_EXPIRY_DAYS

    FROM ANALYTICS.GCP_SCORING

    WHERE COMPANY_ID IS NOT NULL

    GROUP BY COMPANY_ID
),

priority AS (
    SELECT
        *,

        CASE
            WHEN SCORED_GCPS = 0
                THEN 'REVIEW REQUIRED'
            WHEN MAX_RENEWAL_SCORE >= 75
                THEN 'CRITICAL'
            WHEN MAX_RENEWAL_SCORE >= 50
                THEN 'HIGH'
            WHEN MAX_RENEWAL_SCORE >= 25
                THEN 'MEDIUM'
            ELSE 'LOW'
        END AS CUSTOMER_PRIORITY

    FROM company_summary
)

SELECT
    DENSE_RANK() OVER (
        ORDER BY
            MAX_RENEWAL_SCORE DESC NULLS LAST
    ) AS CUSTOMER_RANK,

    *

FROM priority;


SELECT
    CUSTOMER_RANK,
    COMPANY_ID,
    COMPANY_NAME,
    TOTAL_GCPS,
    TOTAL_GTINS,
    MAX_RENEWAL_SCORE,
    CUSTOMER_PRIORITY,
    NEAREST_UPCOMING_EXPIRY_DAYS,
    REVIEW_REQUIRED_GCPS

FROM ANALYTICS.COMPANY_RENEWAL_RANKING

WHERE MAX_RENEWAL_SCORE IS NOT NULL

ORDER BY
    CUSTOMER_RANK,
    COMPANY_ID

LIMIT 20;


SELECT
    ADOPTION_SEGMENT,
    COUNT(*) AS TOTAL_GCPS,
    COUNT_IF(IS_SCOREABLE) AS SCORED_GCPS,
    ROUND(AVG(RENEWAL_SCORE), 2) AS AVG_SCORE
FROM ANALYTICS.GCP_SCORING
GROUP BY ADOPTION_SEGMENT
ORDER BY TOTAL_GCPS DESC;

WITH sensitivity AS (
    SELECT
        GCP,
        RENEWAL_SCORE,

        RENEWAL_SCORE - USAGE_POINTS
            AS SCORE_WITHOUT_USAGE,

        CASE
            WHEN RENEWAL_SCORE >= 50 THEN 1
            ELSE 0
        END AS HIGH_PRIORITY_ORIGINAL,

        CASE
            WHEN RENEWAL_SCORE - USAGE_POINTS >= 50
                THEN 1
            ELSE 0
        END AS HIGH_PRIORITY_WITHOUT_USAGE

    FROM ANALYTICS.GCP_SCORING
    WHERE IS_SCOREABLE
)

SELECT
    COUNT(*) AS SCORED_GCPS,

    COUNT_IF(HIGH_PRIORITY_ORIGINAL = 1)
        AS ORIGINAL_HIGH_PRIORITY,

    COUNT_IF(HIGH_PRIORITY_WITHOUT_USAGE = 1)
        AS HIGH_PRIORITY_WITHOUT_USAGE,

    COUNT_IF(
        HIGH_PRIORITY_ORIGINAL
        <> HIGH_PRIORITY_WITHOUT_USAGE
    ) AS CHANGED_CLASSIFICATIONS

FROM sensitivity;