USE WAREHOUSE GS1_WH;
USE DATABASE GS1_CUSTOMER_INTELLIGENCE;
USE SCHEMA RAW;

-- Table 1: GTIN Activity
CREATE TABLE IF NOT EXISTS GTIN_ACTIVITY (
    GCP VARCHAR(50),
    COMPANY_ID VARCHAR(50),
    COMPANY_NAME VARCHAR(500),
    FIRST_GTIN VARCHAR(50),
    FIRST_GTIN_CREATED_AT VARCHAR(100),
    LAST_GTIN VARCHAR(50),
    LAST_GTIN_CREATED_AT VARCHAR(100),
    TOTAL_GTINS VARCHAR(50)
);

-- Table 2: Subscriptions
CREATE TABLE IF NOT EXISTS SUBSCRIPTIONS (
    GCP VARCHAR(50),
    COMPANY_ID VARCHAR(50),
    COMPANY_NAME VARCHAR(500),
    PLAN VARCHAR(100),
    GCP_REGISTERED_DATE VARCHAR(100),
    SUBSCRIPTION_START_DATE VARCHAR(100),
    SUBSCRIPTION_END_DATE VARCHAR(100),
    VALIDITY_STATUS VARCHAR(100)
);