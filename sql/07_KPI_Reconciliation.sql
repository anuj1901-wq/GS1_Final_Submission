SELECT
    PLAN,
    VALIDITY_STATUS,
    COUNT(*) AS TOTAL_GCPS,
    COUNT_IF(END_DATE >= DATE '2026-10-20')
        AS NOT_EXPIRED_GCPS,
    COUNT_IF(END_DATE < DATE '2026-10-20')
        AS EXPIRED_GCPS
FROM ANALYTICS.CUSTOMER_METRICS
WHERE MATCH_STATUS = 'SUBSCRIPTION_ONLY'
GROUP BY PLAN, VALIDITY_STATUS
ORDER BY TOTAL_GCPS DESC;